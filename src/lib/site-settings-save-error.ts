export function formatSiteSettingsSaveError(message: string) {
  if (message.includes("schema cache") || message.includes("Could not find the")) {
    for (const [column, sqlFile] of Object.entries(COLUMN_SQL_HINTS)) {
      if (message.includes(column)) {
        return `저장 실패: site_settings.${column} 컬럼이 없습니다. Supabase SQL Editor에서 supabase/${sqlFile} 또는 supabase/pending-developer-mode-columns.sql을 실행한 뒤 다시 저장해 주세요.`;
      }
    }

    return "저장 실패: site_settings에 필요한 컬럼이 없습니다. Supabase SQL Editor에서 supabase/pending-developer-mode-columns.sql을 실행한 뒤 다시 저장해 주세요.";
  }

  return `저장 실패: ${message}`;
}
