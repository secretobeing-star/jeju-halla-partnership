drop function if exists public.admin_list_ip_activity_summary();

create function public.admin_list_ip_activity_summary()
returns table (
  ip text,
  post_count bigint,
  comment_count bigint,
  review_count bigint,
  max_status integer,
  last_seen_at timestamptz
)
language sql
security definer
set search_path = public
stable
as $$
  select
    host(l.user_ip) as ip,
    count(*) filter (where l.activity_type = 'post') as post_count,
    count(*) filter (where l.activity_type = 'comment') as comment_count,
    count(*) filter (where l.activity_type = 'review') as review_count,
    coalesce(max(l.status) filter (where l.activity_type = 'post'), 1) as max_status,
    max(l.created_at) as last_seen_at
  from public.ip_activity_log l
  where not l.admin_dismissed
  group by l.user_ip
  order by max(l.created_at) desc;
$$;

drop function if exists public.admin_list_ip_activity_for_ip(text);

create function public.admin_list_ip_activity_for_ip(p_ip text)
returns table (
  id bigint,
  activity_type text,
  source_id uuid,
  board_type text,
  post_id uuid,
  post_title text,
  partner_id uuid,
  partner_name text,
  author_name text,
  title text,
  content_preview text,
  status integer,
  is_hidden boolean,
  source_deleted boolean,
  created_at timestamptz
)
language sql
security definer
set search_path = public
stable
as $$
  select
    l.id,
    l.activity_type,
    l.source_id,
    l.board_type,
    l.post_id,
    l.post_title,
    l.partner_id,
    l.partner_name,
    l.author_name,
    l.title,
    l.content_preview,
    l.status,
    l.is_hidden,
    l.source_deleted,
    l.created_at
  from public.ip_activity_log l
  where not l.admin_dismissed
    and l.user_ip = p_ip::inet
  order by l.created_at desc
  limit 100;
$$;

drop function if exists public.admin_dismiss_ip_activity_log(bigint);

create or replace function public.admin_dismiss_ip_activity_log(p_log_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.ip_activity_log
  set admin_dismissed = true
  where id = p_log_id
    and not admin_dismissed;

  return found;
end;
$$;

grant execute on function public.admin_list_ip_activity_summary() to authenticated;
grant execute on function public.admin_list_ip_activity_for_ip(text) to authenticated;
grant execute on function public.admin_dismiss_ip_activity_log(bigint) to authenticated;

