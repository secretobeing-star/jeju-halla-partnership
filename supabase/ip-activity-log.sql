create trigger ip_activity_log_review_insert
  after insert on public.partner_reviews
  for each row
  execute function public.trg_ip_activity_log_review();

drop trigger if exists ip_activity_log_post_delete on public.board_posts;
create trigger ip_activity_log_post_delete
  before delete on public.board_posts
  for each row
  execute function public.trg_ip_activity_mark_deleted();

drop trigger if exists ip_activity_log_comment_delete on public.board_comments;
create trigger ip_activity_log_comment_delete
  before delete on public.board_comments
  for each row
  execute function public.trg_ip_activity_mark_deleted();

drop trigger if exists ip_activity_log_review_delete on public.partner_reviews;
create trigger ip_activity_log_review_delete
  before delete on public.partner_reviews
  for each row
  execute function public.trg_ip_activity_mark_deleted();

