-- IP 활동 로그: 사용자 삭제 후에도 관리자 IP 목록에 남기고, 관리자가 목록에서 숨길 수 있음

create table if not exists public.ip_activity_log (
  id bigint generated by default as identity primary key,
  user_ip inet not null,
  activity_type text not null check (activity_type in ('post', 'comment', 'review')),
  source_id uuid not null,
  board_type text,
  post_id uuid,
  post_title text,
  partner_id uuid,
  partner_name text,
  author_name text not null,
  title text,
  content_preview text not null default '',
  status integer,
  is_hidden boolean not null default false,
  source_deleted boolean not null default false,
  admin_dismissed boolean not null default false,
  created_at timestamptz not null default now(),
  unique (activity_type, source_id)
);

create index if not exists ip_activity_log_user_ip_idx
  on public.ip_activity_log (user_ip, created_at desc);

create index if not exists ip_activity_log_active_idx
  on public.ip_activity_log (admin_dismissed, created_at desc);

alter table public.ip_activity_log enable row level security;

create or replace function public.mark_ip_activity_source_deleted(
  p_activity_type text,
  p_source_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.ip_activity_log
  set source_deleted = true
  where activity_type = p_activity_type
    and source_id = p_source_id
    and not admin_dismissed;
end;
$$;

create or replace function public.trg_ip_activity_log_post()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.user_ip is null or coalesce(new.is_admin_managed, false) then
    return new;
  end if;

  insert into public.ip_activity_log (
    user_ip,
    activity_type,
    source_id,
    board_type,
    title,
    author_name,
    content_preview,
    status,
    is_hidden,
    created_at
  )
  values (
    new.user_ip,
    'post',
    new.id,
    new.board_type,
    new.title,
    new.author_name,
    left(trim(coalesce(new.content, '')), 500),
    coalesce(new.status, 1),
    coalesce(new.is_hidden, false),
    new.created_at
  )
  on conflict (activity_type, source_id) do nothing;

  return new;
end;
$$;

create or replace function public.trg_ip_activity_log_comment()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_post_title text;
begin
  if new.user_ip is null or coalesce(new.is_admin_managed, false) then
    return new;
  end if;

  select p.title
  into v_post_title
  from public.board_posts p
  where p.id = new.post_id;

  insert into public.ip_activity_log (
    user_ip,
    activity_type,
    source_id,
    post_id,
    post_title,
    author_name,
    content_preview,
    is_hidden,
    created_at
  )
  values (
    new.user_ip,
    'comment',
    new.id,
    new.post_id,
    coalesce(v_post_title, '게시글'),
    new.author_name,
    left(trim(coalesce(new.content, '')), 500),
    coalesce(new.is_hidden, false),
    new.created_at
  )
  on conflict (activity_type, source_id) do nothing;

  return new;
end;
$$;

create or replace function public.trg_ip_activity_log_review()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_partner_name text;
begin
  if new.user_ip is null then
    return new;
  end if;

  select p.name
  into v_partner_name
  from public.partners p
  where p.id = new.partner_id;

  insert into public.ip_activity_log (
    user_ip,
    activity_type,
    source_id,
    partner_id,
    partner_name,
    author_name,
    content_preview,
    is_hidden,
    created_at
  )
  values (
    new.user_ip,
    'review',
    new.id,
    new.partner_id,
    coalesce(v_partner_name, '업체'),
    new.author_name,
    left(trim(coalesce(new.content, '')), 500),
    coalesce(new.is_hidden, false),
    new.created_at
  )
  on conflict (activity_type, source_id) do nothing;

  return new;
end;
$$;

create or replace function public.trg_ip_activity_mark_deleted()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_table_name = 'board_posts' then
    perform public.mark_ip_activity_source_deleted('post', old.id);
  elsif tg_table_name = 'board_comments' then
    perform public.mark_ip_activity_source_deleted('comment', old.id);
  elsif tg_table_name = 'partner_reviews' then
    perform public.mark_ip_activity_source_deleted('review', old.id);
  end if;

  return old;
end;
$$;

drop trigger if exists ip_activity_log_post_insert on public.board_posts;
create trigger ip_activity_log_post_insert
  after insert on public.board_posts
  for each row
  execute function public.trg_ip_activity_log_post();

drop trigger if exists ip_activity_log_comment_insert on public.board_comments;
create trigger ip_activity_log_comment_insert
  after insert on public.board_comments
  for each row
  execute function public.trg_ip_activity_log_comment();

