-- Non-member board IP moderation (status 1~4 + banned_ips)
-- Run in Supabase SQL Editor after board-secret-posts.sql

alter table public.site_settings
  add column if not exists board_ip_moderation_enabled boolean not null default false;

alter table public.board_posts
  add column if not exists user_ip inet;

alter table public.board_posts
  add column if not exists status integer not null default 1;

alter table public.board_posts
  drop constraint if exists board_posts_status_check;

alter table public.board_posts
  add constraint board_posts_status_check check (status between 1 and 4);

create table if not exists public.banned_ips (
  id bigint generated by default as identity primary key,
  ip_address inet not null unique,
  reason text,
  created_at timestamp with time zone not null default now()
);

alter table public.banned_ips enable row level security;

drop policy if exists "banned_ips_admin_all" on public.banned_ips;
create policy "banned_ips_admin_all"
  on public.banned_ips for all to authenticated
  using (true) with check (true);

create index if not exists board_posts_user_ip_idx on public.board_posts (user_ip);
create index if not exists banned_ips_ip_address_idx on public.banned_ips (ip_address);

create or replace function public.is_board_ip_moderation_enabled()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select board_ip_moderation_enabled from public.site_settings where id = 1 limit 1),
    false
  );
$$;

create or replace function public.is_ip_banned(p_ip inet)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.banned_ips b
    where b.ip_address = p_ip
  );
$$;

create or replace function public.resolve_board_post_status_for_ip(p_ip inet)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select greatest(
    1,
    least(
      coalesce(
        (
          select max(p.status)
          from public.board_posts p
          where p.user_ip = p_ip
            and p.password_hash is not null
        ),
        1
      ),
      4
    )
  );
$$;

