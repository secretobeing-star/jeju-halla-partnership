create or replace function public.create_user_board_comment(
  p_post_id uuid,
  p_author_name text,
  p_content text,
  p_password text,
  p_parent_id uuid default null,
  p_is_secret boolean default false,
  p_user_ip inet default null,
  p_voter_key text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  new_id uuid;
  post_hidden boolean;
  parent_post_id uuid;
  parent_hidden boolean;
  store_admin_password boolean;
  secret_enabled boolean;
  ip_enabled boolean;
  normalized_voter_key text;
begin
  normalized_voter_key := nullif(trim(p_voter_key), '');

  if normalized_voter_key is not null and char_length(normalized_voter_key) >= 8
     and public.is_voter_key_banned(normalized_voter_key) then
    raise exception 'Voter key banned';
  end if;

  select is_hidden into post_hidden from board_posts where id = p_post_id;
  if post_hidden is null or post_hidden then
    raise exception 'Post not found';
  end if;

  if p_parent_id is not null then
    select post_id, is_hidden into parent_post_id, parent_hidden
    from board_comments where id = p_parent_id;
    if parent_post_id is null or parent_hidden or parent_post_id <> p_post_id then
      raise exception 'Parent comment not found';
    end if;
  end if;

  if char_length(trim(p_author_name)) = 0 or char_length(trim(p_content)) = 0 then
    raise exception 'Author and content are required';
  end if;

  if char_length(trim(p_password)) < 4 then
    raise exception 'Password must be at least 4 characters';
  end if;

  secret_enabled := public.is_board_secret_comments_enabled();
  if coalesce(p_is_secret, false) and not secret_enabled then
    raise exception 'Secret comments are disabled';
  end if;

  if p_user_ip is not null and public.is_ip_banned(p_user_ip) then
    raise exception 'IP banned';
  end if;

  ip_enabled := public.is_board_ip_moderation_enabled();
  store_admin_password := public.is_admin_user_password_visible();

  insert into board_comments (
    post_id, parent_id, author_name, content, password_hash,
    admin_visible_password, is_secret, user_ip, voter_key
  )
  values (
    p_post_id, p_parent_id, trim(p_author_name), trim(p_content),
    extensions.crypt(p_password, extensions.gen_salt('bf')),
    case when store_admin_password then p_password else null end,
    case when secret_enabled then coalesce(p_is_secret, false) else false end,
    case when ip_enabled then p_user_ip else null end,
    case when normalized_voter_key is not null and char_length(normalized_voter_key) >= 8
      then normalized_voter_key else null end
  )
  returning id into new_id;

  return new_id;
end;
$$;

drop function if exists public.admin_list_voter_key_activity_summary();

create function public.admin_list_voter_key_activity_summary()
returns table (
  voter_key text,
  post_count bigint,
  comment_count bigint,
  review_count bigint,
  max_status integer,
  last_seen_at timestamptz
)
language sql
security definer
set search_path = public
stable
as $$
  select
    l.voter_key,
    count(*) filter (where l.activity_type = 'post') as post_count,
    count(*) filter (where l.activity_type = 'comment') as comment_count,
    count(*) filter (where l.activity_type = 'review') as review_count,
    coalesce(max(l.status) filter (where l.activity_type = 'post'), 1) as max_status,
    max(l.created_at) as last_seen_at
  from public.voter_key_activity_log l
  where not l.admin_dismissed
  group by l.voter_key
  order by max(l.created_at) desc;
$$;

