create or replace function public.is_voter_key_banned(p_voter_key text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.banned_voter_keys b
    where b.voter_key = nullif(trim(p_voter_key), '')
  );
$$;

grant execute on function public.is_voter_key_banned(text) to anon, authenticated;

