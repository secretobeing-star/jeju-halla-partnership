create table if not exists public.voter_key_activity_log (
  id bigint generated by default as identity primary key,
  voter_key text not null,
  activity_type text not null check (activity_type in ('post', 'comment', 'review')),
  source_id uuid not null,
  board_type text,
  post_id uuid,
  post_title text,
  partner_id uuid,
  partner_name text,
  author_name text not null,
  title text,
  content_preview text not null default '',
  status integer,
  is_hidden boolean not null default false,
  source_deleted boolean not null default false,
  admin_dismissed boolean not null default false,
  created_at timestamptz not null default now(),
  unique (activity_type, source_id)
);

create index if not exists voter_key_activity_log_key_idx
  on public.voter_key_activity_log (voter_key, created_at desc);

create index if not exists voter_key_activity_log_active_idx
  on public.voter_key_activity_log (admin_dismissed, created_at desc);

