create or replace function public.trg_voter_key_activity_mark_deleted()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_table_name = 'board_posts' then
    perform public.mark_voter_key_activity_source_deleted('post', old.id);
  elsif tg_table_name = 'board_comments' then
    perform public.mark_voter_key_activity_source_deleted('comment', old.id);
  elsif tg_table_name = 'partner_reviews' then
    perform public.mark_voter_key_activity_source_deleted('review', old.id);
  end if;
  return old;
end;
$$;

