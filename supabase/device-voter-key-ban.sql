create or replace function public.mark_voter_key_activity_source_deleted(
  p_activity_type text,
  p_source_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.voter_key_activity_log
  set source_deleted = true
  where activity_type = p_activity_type
    and source_id = p_source_id
    and not admin_dismissed;
end;
$$;

create or replace function public.trg_voter_key_activity_log_post()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.voter_key is null or char_length(trim(new.voter_key)) < 8 or coalesce(new.is_admin_managed, false) then
    return new;
  end if;

  insert into public.voter_key_activity_log (
    voter_key,
    activity_type,
    source_id,
    board_type,
    title,
    author_name,
    content_preview,
    status,
    is_hidden,
    created_at
  )
  values (
    trim(new.voter_key),
    'post',
    new.id,
    new.board_type,
    new.title,
    new.author_name,
    left(trim(coalesce(new.content, '')), 500),
    coalesce(new.status, 1),
    coalesce(new.is_hidden, false),
    new.created_at
  )
  on conflict (activity_type, source_id) do nothing;

  return new;
end;
$$;

